// Saving an answer as an artifact (#12 §2.11): the SERVER writes the artifact from the stored answer — never the
// model. Markdown writes each linked ref as a link; an HTML page is rendered from the answer's text and blocks,
// with charts drawn as SVG, every string escaped. A diagram saved alone is Mermaid generated here.
import { ASK_REF_TOKEN_RE, type AskBlock, type AskChart, type AskDiagram, type RefView } from "@shared/ai-ask-core";

/** An item's link, absolute: a hash route under the org's page, or its own URL (a PR). */
export const absoluteHref = (href: string | null, appBase: string): string | null =>
  !href ? null : href.startsWith("#") ? `${appBase}/${href}` : href;

const label = (v: RefView): string => (v.num !== undefined && (v.type === "ticket" || v.type === "pr" || v.type === "handoff") ? `#${v.num} ${v.title}` : v.title);

/** Ref tokens → markdown links (linked) or plain words (not linked). A status cell becomes the status word. */
export function tokensToMarkdown(text: string, cites: readonly RefView[], appBase: string): string {
  return text.replace(ASK_REF_TOKEN_RE, (_m, type: string, key: string, status?: string) => {
    const ref = type === "person" ? `${type}:${key.toLowerCase()}` : `${type}:${key}`;
    const v = cites.find((c) => c.ref === ref);
    if (status) return v?.status?.word ?? "";
    if (!v) return `${type} ${key}`;
    const href = absoluteHref(v.href, appBase);
    return href ? `[${label(v)}](${href})` : label(v);
  });
}

/** Mermaid for a diagram (generated by the server, from the structured nodes). */
export function diagramMermaid(d: AskDiagram): string {
  const id = (s: string) => `n_${s.replace(/[^A-Za-z0-9_]/g, "_")}`;
  const text = (s: string) => s.replace(/["\n\r]/g, " ").trim();
  const lines = ["flowchart LR"];
  for (const n of d.nodes) lines.push(`  ${id(n.id)}["${text([n.eyebrow, n.label, n.view?.status?.word].filter(Boolean).join(" · "))}"]`);
  for (const [a, b] of d.edges) lines.push(`  ${id(a)} --> ${id(b)}`);
  return lines.join("\n");
}

function blockMarkdown(b: AskBlock, appBase: string): string {
  switch (b.kind) {
    case "items": return b.items.map((v) => {
      const href = absoluteHref(v.href, appBase);
      return `- ${href ? `[${label(v)}](${href})` : label(v)}${v.status ? ` · ${v.status.word}` : ""}`;
    }).join("\n");
    case "chart": return [`**${b.chart.title}** (${b.chart.total} ${b.chart.unit})`, "", `| | ${b.chart.unit} |`, "| --- | ---: |",
      ...b.chart.rows.map((r) => `| ${r.label} | ${r.value} |`), `| Total | ${b.chart.total} |`].join("\n");
    case "themes": return b.themes.lanes.length
      ? [`**${b.themes.title}** (${b.themes.caption})`, "", `| Theme | ${b.themes.weeks.join(" | ")} |`, `| --- |${b.themes.weeks.map(() => " ---: |").join("")}`,
        ...b.themes.lanes.map((l) => `| ${l.theme} | ${l.values.map((v) => `${Math.round(v * 100)}%`).join(" | ")} |`)].join("\n")
      : `**${b.themes.title}**: no themes yet.`;
    case "diagram": return [`**${b.diagram.title}**${b.diagram.caption ? `: ${b.diagram.caption}` : ""}`, "", "```mermaid", diagramMermaid(b.diagram), "```"].join("\n");
    case "not_found": return [`I couldn't find "${b.notFound.query}" in Trov.`, ...b.notFound.searched.map((s) => `- ${s.area}: ${s.scope} (no matches)`)].join("\n");
    case "save_form": return "";
  }
}

export interface SavedPart { who: "person" | "trov"; mode?: string; text: string; blocks: AskBlock[]; cites: RefView[]; at: string }

/** The saved part as Markdown: the answer (or each exchange of the thread), refs as links. */
export function partsMarkdown(title: string, parts: readonly SavedPart[], appBase: string): string {
  const out = [`# ${title}`];
  for (const p of parts) {
    const body = [tokensToMarkdown(p.text, p.cites, appBase), ...p.blocks.map((b) => blockMarkdown(b, appBase)).filter(Boolean)].filter((s) => s.trim()).join("\n\n");
    out.push(parts.length > 1 ? `**${p.who === "person" ? "You" : `Trov${p.mode ? ` (${p.mode})` : ""}`}** · ${p.at.slice(0, 16).replace("T", " ")}\n\n${body}` : body);
  }
  return `${out.join("\n\n---\n\n")}\n`;
}

// ── HTML ─────────────────────────────────────────────────────────────────────

const esc = (s: string): string => s.replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]!);
const safeHref = (h: string | null): string | null => (h && /^(https?:\/\/|#)/.test(h) ? h : null);

/** Inline markdown on ALREADY-escaped text: code, bold, italic, and the links `tokensToMarkdown` made. */
function inlineHtml(s: string): string {
  return s
    .replace(/`([^`]+)`/g, "<code>$1</code>")
    .replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>")
    .replace(/(^|[^*])\*([^*]+)\*/g, "$1<em>$2</em>")
    .replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, (_m, t: string, h: string) => {
      const href = safeHref(h.replace(/&amp;/g, "&"));
      return href ? `<a href="${esc(href)}">${t}</a>` : t;
    });
}

/** A small, safe markdown → HTML: headings, paragraphs, lists, pipe tables and fenced code. Everything escaped. */
export function markdownHtml(md: string): string {
  const out: string[] = [];
  const lines = md.split("\n");
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (/^```/.test(line)) {
      const code: string[] = [];
      for (i++; i < lines.length && !/^```/.test(lines[i]); i++) code.push(lines[i]);
      out.push(`<pre><code>${esc(code.join("\n"))}</code></pre>`);
    } else if (/^#{1,6}\s/.test(line)) {
      const n = line.match(/^#+/)![0].length;
      out.push(`<h${n}>${inlineHtml(esc(line.replace(/^#+\s*/, "")))}</h${n}>`);
    } else if (/^\s*[-*]\s+/.test(line)) {
      const items: string[] = [];
      for (; i < lines.length && /^\s*[-*]\s+/.test(lines[i]); i++) items.push(`<li>${inlineHtml(esc(lines[i].replace(/^\s*[-*]\s+/, "")))}</li>`);
      i--;
      out.push(`<ul>${items.join("")}</ul>`);
    } else if (/^\s*\|/.test(line)) {
      const rows: string[][] = [];
      for (; i < lines.length && /^\s*\|/.test(lines[i]); i++) rows.push(lines[i].trim().replace(/^\||\|$/g, "").split("|").map((c) => c.trim()));
      i--;
      const body = rows.filter((r) => !r.every((c) => /^:?-{3,}:?$/.test(c)));
      const [head, ...rest] = body;
      out.push(`<table><thead><tr>${(head ?? []).map((c) => `<th>${inlineHtml(esc(c))}</th>`).join("")}</tr></thead><tbody>${rest.map((r) => `<tr>${r.map((c) => `<td>${inlineHtml(esc(c))}</td>`).join("")}</tr>`).join("")}</tbody></table>`);
    } else if (/^---+$/.test(line.trim())) {
      out.push("<hr>");
    } else if (line.trim()) {
      const para: string[] = [line];
      for (i++; i < lines.length && lines[i].trim() && !/^(#{1,6}\s|```|\s*[-*]\s+|\s*\|)/.test(lines[i]); i++) para.push(lines[i]);
      i--;
      out.push(`<p>${inlineHtml(esc(para.join(" ")))}</p>`);
    }
  }
  return out.join("\n");
}

/** A bar chart as SVG, from the server's numbers only. */
export function chartSvg(c: AskChart): string {
  const w = 560, h = 200, pad = 28, n = Math.max(1, c.rows.length);
  const max = Math.max(1, ...c.rows.map((r) => r.value));
  const bw = (w - pad * 2) / n;
  const bars = c.rows.map((r, i) => {
    const bh = Math.round(((h - pad * 2) * r.value) / max);
    const x = pad + i * bw + bw * 0.15, y = h - pad - bh;
    return `<rect x="${x.toFixed(1)}" y="${y}" width="${(bw * 0.7).toFixed(1)}" height="${bh}" fill="#3b7a57"><title>${esc(`${r.label}: ${r.value} ${c.unit}`)}</title></rect>`
      + `<text x="${(x + bw * 0.35).toFixed(1)}" y="${h - pad + 14}" font-size="10" text-anchor="middle" fill="#555">${esc(r.label)}</text>`;
  }).join("");
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" role="img" aria-label="${esc(`${c.title}: ${c.total} ${c.unit}`)}">${bars}</svg>`;
}

function blockHtml(b: AskBlock, appBase: string): string {
  switch (b.kind) {
    case "chart": return `<figure><figcaption><strong>${esc(b.chart.title)}</strong> · ${b.chart.total} ${esc(b.chart.unit)} · Data from Trov</figcaption>${chartSvg(b.chart)}</figure>`;
    case "diagram": return `<figure><figcaption><strong>${esc(b.diagram.title)}</strong>${b.diagram.caption ? ` · ${esc(b.diagram.caption)}` : ""}</figcaption><ol class="chain">${b.diagram.nodes
      .map((n) => `<li>${n.eyebrow ? `<small>${esc(n.eyebrow)}</small><br>` : ""}${esc(n.label)}${n.view?.status ? ` <em>${esc(n.view.status.word)}</em>` : ""}</li>`).join("")}</ol></figure>`;
    case "save_form": return "";
    default: return markdownHtml(blockMarkdown(b, appBase));
  }
}

/** The saved part as a standalone HTML page (the artifact viewer renders it sandboxed). */
export function partsHtml(title: string, parts: readonly SavedPart[], appBase: string, subtitle: string): string {
  const body = parts.map((p) => [
    parts.length > 1 ? `<h3>${p.who === "person" ? "You" : "Trov"}</h3>` : "",
    markdownHtml(tokensToMarkdown(p.text, p.cites, appBase)),
    ...p.blocks.map((b) => blockHtml(b, appBase)),
  ].join("\n")).join("\n<hr>\n");
  return `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>${esc(title)}</title>
<style>body{font:15px/1.55 system-ui,sans-serif;max-width:760px;margin:32px auto;padding:0 16px;color:#1d1d1b;background:#fff}h1{font-size:24px}table{border-collapse:collapse}td,th{border:1px solid #ddd;padding:4px 8px;text-align:left}figure{margin:16px 0}.chain{display:flex;gap:8px;list-style:none;padding:0;flex-wrap:wrap}.chain li{border:1px solid #ccc;border-radius:8px;padding:6px 10px}small{color:#666}a{color:#2f6b4a}</style></head>
<body><p><small>${esc(subtitle)}</small></p><h1>${esc(title)}</h1>
${body}
</body></html>`;
}
